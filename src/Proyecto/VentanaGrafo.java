    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed


Graphics g = jPanel2.getGraphics();

int largo = 470;
int ancho = 575;
g.setColor(Color.blue);
g.fillRect(0, 0, largo, ancho);

//Matriz para las posiciones de los nodos
int matriz[][] = new int[tamanio][2];


g.setColor(Color.red);
int l = 30;

//posiciones
for (int i = 0; i < a.t; i++) {
    int posX = (int) (Math.random() * (largo - l)); // Posicion X aleatoria
    int posY = (int) (Math.random() * (ancho - l)); // Posicion Y aleatoria
    
    matriz[i][0] = posX;
    matriz[i][1] = posY;
    
    g.fillOval(posX, posY, l, l);
}

// Nombre de los nodos
g.setColor(Color.white);
g.setFont(new Font("Tahoma", Font.BOLD, 12));
for (int i = 0; i < a.t; i++) {
    g.drawString("" + a.x[i], matriz[i][0] + 10, matriz[i][1] + 20);
}

//Aristas
g.setColor(Color.YELLOW);
for (int i = 0; i < a.t; i++) {
    for (int j = 0; j < a.t; j++) {
        if (a.matriz[i][j] != 0) {
            g.drawLine(matriz[i][0] + l/2, matriz[i][1] + l/2, matriz[j][0] + l/2, matriz[j][1] + l/2);
        }
    }
}

        
    }//GEN-LAST:event_jButton4ActionPerformed

